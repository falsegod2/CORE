"""Commit a checkpoint directory atomically. Never delete replay or unrelated projects."""
from __future__ import annotations
import contextlib
import gzip
import hashlib
import json
import os
import pickle
import shutil
import uuid
from pathlib import Path

def sha256(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()

def atomic_json(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name('.' + path.name + '.' + uuid.uuid4().hex)
    try:
        with tmp.open('w', encoding='utf8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)

class RunLock:

    def __init__(self, path):
        self.path = Path(path)

    def __enter__(self):
        import fcntl
        self.f = self.path.open('a+')
        try:
            fcntl.flock(self.f, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            self.f.close()
            raise RuntimeError(f'A process already owns {self.path.parent}')
        return self

    def __exit__(self, *args):
        self.f.close()

class Checkpoints:

    def __init__(self, root, keep=2, min_free_gb=8):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        self.keep = max(1, int(keep))
        self.reserve = int(min_free_gb * (1 << 30))

    def require_space(self):
        if shutil.disk_usage(self.root).free < self.reserve:
            raise OSError('Insufficient free space; old complete checkpoints kept')

    def save(self, step, state, identity):
        self.require_space()
        tmp = self.root / ('.incomplete_' + uuid.uuid4().hex)
        tmp.mkdir()
        target = self.root / f'step_{int(step):010d}'
        if target.exists():
            raise FileExistsError(target)
        try:
            manager = self

            class CheckedFile:

                def __init__(self, file):
                    self.file = file
                    self.bytes = 0

                def write(self, data):
                    self.bytes += len(data)
                    if self.bytes >= 16 << 20:
                        manager.require_space()
                        self.bytes = 0
                    return self.file.write(data)

                def flush(self):
                    return self.file.flush()
            with (tmp / 'state.pkl.gz').open('wb') as file:
                with gzip.GzipFile(fileobj=CheckedFile(file), mode='wb', compresslevel=1) as compressed:
                    pickle.dump(state, compressed, protocol=5)
                file.flush()
                os.fsync(file.fileno())
            atomic_json(tmp / 'manifest.json', {'step': int(step), 'identity': identity, 'sha256': sha256(tmp / 'state.pkl.gz')})
            os.rename(tmp, target)
            atomic_json(self.root / 'latest.json', {'directory': target.name})
        except BaseException:
            shutil.rmtree(tmp, ignore_errors=True)
            raise
        # Only this manager's committed checkpoint directories are eligible.
        complete = sorted((p for p in self.root.glob('step_*') if (p / 'manifest.json').is_file()))
        for p in complete[:-self.keep]:
            shutil.rmtree(p)
        return target

    def load(self, identity, step=None):
        pointer = json.loads((self.root / 'latest.json').read_text())
        name = pointer['directory'] if step is None else f'step_{int(step):010d}'
        if Path(name).name != name:
            raise ValueError('Unsafe checkpoint pointer')
        path = self.root / name
        meta = json.loads((path / 'manifest.json').read_text())
        if meta['identity'] != identity:
            raise ValueError('Checkpoint experiment identity mismatch')
        if sha256(path / 'state.pkl.gz') != meta['sha256']:
            raise ValueError('Checkpoint checksum mismatch')
        # Only load trusted checkpoints generated by this suite, never arbitrary downloads.
        with gzip.open(path / 'state.pkl.gz', 'rb') as f:
            return pickle.load(f)
